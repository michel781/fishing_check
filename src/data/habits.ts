export const getHabit = (id: string): Habit | undefined => HABITS[id];

/** 사실 하나의 근거 수준: 출처 중 가장 공신력 있는 것 */
const RANK: Evidence[] = ["기관", "논문", "백과", "기사", "현장", "추론"];
export function factEvidence(h: Habit, src: number[] | Evidence): Evidence {
  if (!Array.isArray(src)) return src;
  if (!src.length) return "추론";
  return src.map((i) => h.src[i][2]).sort((a, b) => RANK.indexOf(a) - RANK.indexOf(b))[0];
}
